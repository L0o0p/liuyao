/// 八卦符号对应表
/// 用于更清晰地表示卦象
const Map<String, String> baguaSymbols = {
  "天": "☰", // 乾
  "地": "☷", // 坤
  "雷": "☳", // 震
  "风": "☴", // 巽
  "水": "☵", // 坎
  "火": "☲", // 离
  "山": "☶", // 艮
  "泽": "☱", // 兑
};

/// 获取卦象的符号表示
/// 例如：getGuaSymbol("火天") 返回 "☲☰"
String getGuaSymbol(String guaXiang) {
  if (guaXiang.length != 2) return guaXiang;

  final shangGua = guaXiang[0];
  final xiaGua = guaXiang[1];

  final shangSymbol = baguaSymbols[shangGua] ?? shangGua;
  final xiaSymbol = baguaSymbols[xiaGua] ?? xiaGua;

  return '$shangSymbol$xiaSymbol';
}

/// 获取所有卦名列表
List<String> getAllGuaNames() {
  return guaMap.keys.toList();
}

/// 获取所有卦象列表
List<String> getAllGuaXiang() {
  return guaMap.values.toList();
}

/// 根据卦名获取卦象
String? getGuaXiang(String guaName) {
  return guaMap[guaName];
}

/// 根据卦象获取卦名
String? getGuaName(String guaXiang) {
  for (final entry in guaMap.entries) {
    if (entry.value == guaXiang) {
      return entry.key;
    }
  }
  return null;
}
